import {spawn} from 'node:child_process';
import fs from 'node:fs';
import path from 'node:path';
import {fileURLToPath} from 'node:url';
const root=path.resolve(path.dirname(fileURLToPath(import.meta.url)),'../..');
const exe=process.env.BLENDER_AGENT_EXE||process.env.DSH_BLENDER_EXE;
if(!exe)throw Error('Set BLENDER_AGENT_EXE to a real Blender 4.x/5.x executable. This test never uses a mock.');
const out=path.resolve(process.argv[2]||path.join(root,'tmp/runtime-regression'));
fs.mkdirSync(out,{recursive:true});
const {GPU_PRELUDE}=await import('../../bridge/runtime/paths.mjs');
fs.writeFileSync(path.join(out,'gpu-prelude.py'),GPU_PRELUDE.replaceAll('__DSH_ENGINE__',JSON.stringify('eevee')).replaceAll('__DSH_GPU_MANUAL__','False'));
const child=spawn(exe,['-b','--factory-startup','--python-exit-code','1','--python',path.join(root,'tests/runtime/runtime_regression.py'),'--',out],{windowsHide:true,stdio:['ignore','pipe','pipe']});
const stdout=fs.createWriteStream(path.join(out,'stdout.log'));const stderr=fs.createWriteStream(path.join(out,'stderr.log'));
child.stdout.pipe(stdout);child.stderr.pipe(stderr);
const code=await new Promise((resolve,reject)=>{child.once('error',reject);child.once('exit',resolve);});
if(code!==0)throw Error('Real Blender regression failed; inspect '+out);
const result=JSON.parse(fs.readFileSync(path.join(out,'regression.json'),'utf8'));
if(!result.ok)throw Error('Regression verdict is not pass');
console.log(JSON.stringify(result,null,2));
